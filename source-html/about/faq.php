    <h3>合作任务玩家最常犯的严重错误是什么？</h3>
    <p>过度专注于额外目标。与任务胜利相比，额外目标提供的经验值很少。然而，许多玩家一心完成额外目标，最后却输掉整个任务。像<a href="/missions/cradleofdeath">死亡摇篮</a>这样的任务尤其容易让缺乏经验的玩家落入这个陷阱。</p>
